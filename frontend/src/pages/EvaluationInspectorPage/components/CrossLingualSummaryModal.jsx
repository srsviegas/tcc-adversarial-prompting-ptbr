import React, { useState } from 'react';
import {
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  Button,
  Stack,
  Typography,
  IconButton,
  Box,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Paper,
  Chip,
  Alert,
  Tooltip,
} from '@mui/material';
import { FontAwesomeIcon } from '@fortawesome/react-fontawesome';
import {
  faXmark,
  faScaleBalanced,
  faCopy,
  faCheck,
  faLanguage,
  faArrowTrendUp,
} from '@fortawesome/free-solid-svg-icons';

export function CrossLingualSummaryModal({ open, onClose, summary }) {
  const [copiedLatex, setCopiedLatex] = useState(false);

  if (!summary) return null;

  const byLang = summary.by_language || {};
  const pt = byLang['pt-BR'] || {};
  const en = byLang.en || {};
  const gap = byLang.cross_lingual_gap_pt_minus_en ?? (
    pt.consensus_asr_percentage !== undefined && en.consensus_asr_percentage !== undefined
      ? Number((pt.consensus_asr_percentage - en.consensus_asr_percentage).toFixed(2))
      : null
  );

  const evaluatorNames = Object.keys(pt.evaluators || {});

  // Generate LaTeX table snippet
  const generateLatex = () => {
    let latex = `% Cross-Lingual Vulnerability Summary (Generated by TCC Benchmark)\n`;
    latex += `\\begin{table}[htbp]\n`;
    latex += `\\centering\n`;
    latex += `\\caption{Cross-Lingual Vulnerability Comparison between Portuguese (pt-BR) and English (en)}\n`;
    latex += `\\label{tab:cross_lingual_asr}\n`;
    latex += `\\begin{tabular}{lccccr}\n`;
    latex += `\\hline\n`;
    latex += `\\textbf{Evaluator / Method} & \\textbf{pt-BR (Dang/Total)} & \\textbf{pt-BR ASR} & \\textbf{en (Dang/Total)} & \\textbf{en ASR} & \\textbf{$\\Delta$ (pt - en)} \\\\\n`;
    latex += `\\hline\n`;
    latex += `Consensus ($\\ge 2$ Majority) & ${pt.consensus_dangerous?.toLocaleString()}/${pt.quorum_rows?.toLocaleString()} & ${pt.consensus_asr_percentage}\\% & ${en.consensus_dangerous?.toLocaleString()}/${en.quorum_rows?.toLocaleString()} & ${en.consensus_asr_percentage}\\% & +${gap}\\% \\\\\n`;

    evaluatorNames.forEach((ev) => {
      const ptEv = pt.evaluators?.[ev] || {};
      const enEv = en.evaluators?.[ev] || {};
      const diff = Number((ptEv.asr_percentage - enEv.asr_percentage).toFixed(2));
      const diffStr = diff >= 0 ? `+${diff}\\%` : `${diff}\\%`;
      latex += `${ev} & ${ptEv.flagged_dangerous?.toLocaleString()}/${ptEv.total_evaluated?.toLocaleString()} & ${ptEv.asr_percentage}\\% & ${enEv.flagged_dangerous?.toLocaleString()}/${enEv.total_evaluated?.toLocaleString()} & ${enEv.asr_percentage}\\% & ${diffStr} \\\\\n`;
    });

    latex += `\\hline\n`;
    latex += `\\end{tabular}\n`;
    latex += `\\end{table}\n`;
    return latex;
  };

  const handleCopyLatex = () => {
    navigator.clipboard.writeText(generateLatex());
    setCopiedLatex(true);
    setTimeout(() => setCopiedLatex(false), 2000);
  };

  const interAgreement = summary.inter_evaluator_agreement || {};

  return (
    <Dialog
      open={open}
      onClose={onClose}
      maxWidth="md"
      fullWidth
      sx={{
        '& .MuiDialog-paper': {
          borderRadius: 3,
        },
      }}
    >
      <DialogTitle sx={{ p: 2.5, borderBottom: '1px solid #e2e8f0', bgcolor: '#f8fafc' }}>
        <Stack direction="row" alignItems="center" justifyContent="space-between">
          <Stack direction="row" spacing={1.5} alignItems="center">
            <Box
              sx={{
                width: 36,
                height: 36,
                borderRadius: 2,
                bgcolor: '#f5f3ff',
                color: '#7c3aed',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                border: '1px solid #ddd6fe',
              }}
            >
              <FontAwesomeIcon icon={faLanguage} style={{ fontSize: '1.1rem' }} />
            </Box>
            <Box>
              <Typography variant="subtitle1" fontWeight={800} color="#0f172a">
                Cross-Lingual Vulnerability Benchmark (pt-BR vs English)
              </Typography>
              <Typography variant="caption" color="#64748b">
                Evaluation results across {summary.total_files} benchmark files and {summary.total_rows_evaluated?.toLocaleString()} iterations.
              </Typography>
            </Box>
          </Stack>
          <IconButton size="small" onClick={onClose}>
            <FontAwesomeIcon icon={faXmark} />
          </IconButton>
        </Stack>
      </DialogTitle>

      <DialogContent sx={{ p: 3 }}>
        {/* Highlight Cards Row */}
        <Stack direction={{ xs: 'column', sm: 'row' }} spacing={2} mb={3}>
          <Box
            sx={{
              flex: 1,
              p: 2,
              borderRadius: 2,
              bgcolor: '#faf5ff',
              border: '1px solid #e9d5ff',
            }}
          >
            <Typography variant="caption" fontWeight={700} color="#7e22ce" display="block">
              🇧🇷 PORTUGUESE (pt-BR) ASR
            </Typography>
            <Typography variant="h5" fontWeight={800} color="#581c87" my={0.5}>
              {pt.consensus_asr_percentage}%
            </Typography>
            <Typography variant="caption" color="#6b21a8">
              {pt.consensus_dangerous?.toLocaleString()} / {pt.quorum_rows?.toLocaleString()} Quorum Rows
            </Typography>
          </Box>

          <Box
            sx={{
              flex: 1,
              p: 2,
              borderRadius: 2,
              bgcolor: '#f0fdfa',
              border: '1px solid #99f6e4',
            }}
          >
            <Typography variant="caption" fontWeight={700} color="#0f766e" display="block">
              🇺🇸 ENGLISH (en) ASR
            </Typography>
            <Typography variant="h5" fontWeight={800} color="#115e59" my={0.5}>
              {en.consensus_asr_percentage}%
            </Typography>
            <Typography variant="caption" color="#134e4a">
              {en.consensus_dangerous?.toLocaleString()} / {en.quorum_rows?.toLocaleString()} Quorum Rows
            </Typography>
          </Box>

          <Box
            sx={{
              flex: 1,
              p: 2,
              borderRadius: 2,
              bgcolor: gap > 0 ? '#fff1f2' : '#f0fdf4',
              border: '1px solid',
              borderColor: gap > 0 ? '#fecdd3' : '#bbf7d0',
            }}
          >
            <Typography variant="caption" fontWeight={700} color={gap > 0 ? '#e11d48' : '#16a34a'} display="block">
              ⚡ CROSS-LINGUAL GAP (pt-BR − en)
            </Typography>
            <Typography variant="h5" fontWeight={800} color={gap > 0 ? '#9f1239' : '#166534'} my={0.5}>
              {gap > 0 ? `+${gap}%` : `${gap}%`}
            </Typography>
            <Typography variant="caption" color={gap > 0 ? '#881337' : '#14532d'}>
              {gap > 0 ? 'Higher vulnerability in Portuguese' : 'Lower vulnerability in Portuguese'}
            </Typography>
          </Box>
        </Stack>

        {/* Comparison Table */}
        <Typography variant="subtitle2" fontWeight={800} color="#0f172a" mb={1}>
          Breakdown by Evaluator Architecture
        </Typography>
        <TableContainer component={Paper} variant="outlined" sx={{ borderRadius: 2, mb: 3 }}>
          <Table size="small">
            <TableHead sx={{ bgcolor: '#f8fafc' }}>
              <TableRow>
                <TableCell sx={{ fontWeight: 700, color: '#334155' }}>Evaluator / Method</TableCell>
                <TableCell align="right" sx={{ fontWeight: 700, color: '#7e22ce' }}>pt-BR Dangerous / Total</TableCell>
                <TableCell align="right" sx={{ fontWeight: 700, color: '#7e22ce' }}>pt-BR ASR</TableCell>
                <TableCell align="right" sx={{ fontWeight: 700, color: '#0f766e' }}>en Dangerous / Total</TableCell>
                <TableCell align="right" sx={{ fontWeight: 700, color: '#0f766e' }}>en ASR</TableCell>
                <TableCell align="right" sx={{ fontWeight: 700, color: '#b45309' }}>Delta (pt − en)</TableCell>
              </TableRow>
            </TableHead>
            <TableBody>
              {/* Consensus Row */}
              <TableRow sx={{ bgcolor: '#faf5ff', '& td': { fontWeight: 700 } }}>
                <TableCell>
                  <Stack direction="row" spacing={1} alignItems="center">
                    <FontAwesomeIcon icon={faScaleBalanced} style={{ color: '#7c3aed' }} />
                    <span>Consensus (≥ 2 Majority)</span>
                  </Stack>
                </TableCell>
                <TableCell align="right">{pt.consensus_dangerous?.toLocaleString()} / {pt.quorum_rows?.toLocaleString()}</TableCell>
                <TableCell align="right" sx={{ color: '#6b21a8' }}>{pt.consensus_asr_percentage}%</TableCell>
                <TableCell align="right">{en.consensus_dangerous?.toLocaleString()} / {en.quorum_rows?.toLocaleString()}</TableCell>
                <TableCell align="right" sx={{ color: '#0f766e' }}>{en.consensus_asr_percentage}%</TableCell>
                <TableCell align="right" sx={{ color: gap > 0 ? '#dc2626' : '#16a34a' }}>
                  {gap > 0 ? `+${gap}%` : `${gap}%`}
                </TableCell>
              </TableRow>

              {/* Individual Evaluator Rows */}
              {evaluatorNames.map((ev) => {
                const ptEv = pt.evaluators?.[ev] || {};
                const enEv = en.evaluators?.[ev] || {};
                const diff = Number((ptEv.asr_percentage - enEv.asr_percentage).toFixed(2));
                return (
                  <TableRow key={ev} hover>
                    <TableCell sx={{ fontWeight: 600, color: '#1e293b' }}>{ev}</TableCell>
                    <TableCell align="right">{ptEv.flagged_dangerous?.toLocaleString()} / {ptEv.total_evaluated?.toLocaleString()}</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#7e22ce' }}>{ptEv.asr_percentage}%</TableCell>
                    <TableCell align="right">{enEv.flagged_dangerous?.toLocaleString()} / {enEv.total_evaluated?.toLocaleString()}</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#0f766e' }}>{enEv.asr_percentage}%</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: diff > 0 ? '#dc2626' : '#16a34a' }}>
                      {diff > 0 ? `+${diff}%` : `${diff}%`}
                    </TableCell>
                  </TableRow>
                );
              })}
            </TableBody>
          </Table>
        </TableContainer>

        {/* Inter-Evaluator Agreement */}
        {Object.keys(interAgreement).length > 0 && (
          <>
            <Typography variant="subtitle2" fontWeight={800} color="#0f172a" mb={1}>
              Inter-Evaluator Reliability (Cohen's Kappa)
            </Typography>
            <TableContainer component={Paper} variant="outlined" sx={{ borderRadius: 2 }}>
              <Table size="small">
                <TableHead sx={{ bgcolor: '#f8fafc' }}>
                  <TableRow>
                    <TableCell sx={{ fontWeight: 700, color: '#334155' }}>Evaluator Pair</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#334155' }}>Overlapping Samples</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#16a34a' }}>Observed Agreement</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#7c3aed' }}>Cohen's Kappa (κ)</TableCell>
                    <TableCell align="right" sx={{ fontWeight: 700, color: '#334155' }}>Interpretation</TableCell>
                  </TableRow>
                </TableHead>
                <TableBody>
                  {Object.entries(interAgreement).map(([pair, ag]) => {
                    if (ag.overlap === 0) return null;
                    return (
                      <TableRow key={pair} hover>
                        <TableCell sx={{ fontWeight: 600, color: '#1e293b' }}>{pair}</TableCell>
                        <TableCell align="right">{ag.overlap?.toLocaleString()}</TableCell>
                        <TableCell align="right" sx={{ fontWeight: 700, color: '#16a34a' }}>
                          {(ag.observed_agreement * 100).toFixed(1)}%
                        </TableCell>
                        <TableCell align="right" sx={{ fontWeight: 700, color: '#7c3aed' }}>
                          {ag.cohen_kappa !== null ? ag.cohen_kappa.toFixed(4) : 'N/A'}
                        </TableCell>
                        <TableCell align="right">
                          <Chip label={ag.interpretation} size="small" sx={{ fontSize: '0.7rem', height: 20 }} />
                        </TableCell>
                      </TableRow>
                    );
                  })}
                </TableBody>
              </Table>
            </TableContainer>
          </>
        )}
      </DialogContent>

      <DialogActions sx={{ p: 2, borderTop: '1px solid #e2e8f0', justifyContent: 'space-between' }}>
        <Button
          variant="outlined"
          onClick={handleCopyLatex}
          startIcon={<FontAwesomeIcon icon={copiedLatex ? faCheck : faCopy} />}
          sx={{
            borderColor: copiedLatex ? '#22c55e' : '#cbd5e1',
            color: copiedLatex ? '#16a34a' : '#475569',
            fontWeight: 600,
          }}
        >
          {copiedLatex ? 'Copied LaTeX Code!' : 'Copy LaTeX Table'}
        </Button>
        <Button variant="contained" onClick={onClose} sx={{ bgcolor: '#0f172a', fontWeight: 600 }}>
          Close
        </Button>
      </DialogActions>
    </Dialog>
  );
}
